from manim import *

BG='#101B27'; INK='#EDF3EF'; MUTED='#A8B8B8'; TEAL='#6CD5C0'; GOLD='#F2C66D'; CORAL='#F08E7F'; LINE='#435763'
FONT='Hiragino Sans GB'
def txt(s,size=30,color=INK,weight=NORMAL): return Text(s,font=FONT,font_size=size,color=color,weight=weight)
class CacheStory(Scene):
 def construct(self):
  self.camera.background_color=BG
  # Stable spatial anchors: reader, cache, source. The token is the requested data.
  title=txt('缓存：先看手边，再去取',42,weight=BOLD).to_edge(UP,buff=.42)
  sub=txt('用一本书，理解两种结果',23,MUTED).next_to(title,DOWN,buff=.18)
  self.play(FadeIn(title,shift=UP*.12),FadeIn(sub),run_time=.8); self.wait(2.2)
  self.play(FadeOut(sub),title.animate.scale(.72).to_corner(UL,buff=.45),run_time=.6)
  # Icons: reader is a person, cache a small open shelf, source a book stack.
  reader=VGroup(Circle(radius=.28,stroke_color=INK,stroke_width=3).shift(UP*.34),Arc(radius=.53,start_angle=0,angle=PI,stroke_color=INK,stroke_width=3).shift(DOWN*.27)).move_to(LEFT*5.0+UP*.35)
  cache=VGroup(RoundedRectangle(width=2.15,height=1.55,corner_radius=.16,stroke_color=TEAL,stroke_width=3,fill_color='#183B3D',fill_opacity=.65),Line(LEFT*.86+DOWN*.34,RIGHT*.86+DOWN*.34,color=TEAL,stroke_width=3)).move_to(LEFT*.6+UP*.35)
  source=VGroup(*[RoundedRectangle(width=1.65,height=.27,corner_radius=.07,stroke_color=GOLD,stroke_width=2,fill_color='#594A31',fill_opacity=.8).shift(UP*(i*.33)) for i in range(3)]).move_to(RIGHT*4.5+UP*.2)
  labels=VGroup(txt('你',26).next_to(reader,DOWN,buff=.48),txt('缓存 / 手边书架',26,TEAL).next_to(cache,DOWN,buff=.32),txt('数据源 / 远处书库',26,GOLD).next_to(source,DOWN,buff=.45))
  route1=Line(reader.get_right()+RIGHT*.22,cache.get_left()+LEFT*.23,color=LINE,stroke_width=2)
  route2=Line(cache.get_right()+RIGHT*.22,source.get_left()+LEFT*.23,color=LINE,stroke_width=2)
  self.play(LaggedStart(FadeIn(reader),FadeIn(cache),FadeIn(source),lag_ratio=.18),Create(route1),Create(route2),FadeIn(labels),run_time=1.3)
  book=VGroup(RoundedRectangle(width=.48,height=.65,corner_radius=.06,fill_color=TEAL,fill_opacity=1,stroke_width=0),Line(UP*.23+LEFT*.12,DOWN*.23+LEFT*.12,color=BG,stroke_width=2)).move_to(cache.get_center()+UP*.12)
  self.play(FadeIn(book,scale=.8),run_time=.4)
  cap=txt('想读的书，已经在手边',31).move_to(DOWN*2.35)
  tag=txt('命中 HIT',28,TEAL,weight=BOLD).move_to(UP*2.0+LEFT*.6)
  self.play(FadeIn(tag),FadeIn(cap),run_time=.5)
  self.play(book.animate.move_to(reader.get_center()+DOWN*.25),run_time=1.15,rate_func=smooth)
  self.wait(2.3)
  self.play(FadeOut(book),FadeOut(tag),FadeOut(cap),run_time=.45)
  # Miss: cache is empty. Request travels to cache, then source; the same book returns and a copy stays.
  cap2=txt('手边没有：先去书库取',31).move_to(DOWN*2.35)
  tag2=txt('未命中 MISS',28,CORAL,weight=BOLD).move_to(UP*2.0+LEFT*.6)
  req=VGroup(Circle(radius=.15,fill_color=CORAL,fill_opacity=1,stroke_width=0),txt('?',16,BG,weight=BOLD)).move_to(reader.get_center()+RIGHT*.5)
  self.play(FadeIn(tag2),FadeIn(cap2),FadeIn(req),run_time=.5)
  self.play(req.animate.move_to(cache.get_center()),run_time=.8,rate_func=linear)
  self.play(Indicate(cache,color=CORAL,scale_factor=1.04),run_time=.5)
  self.play(req.animate.move_to(source.get_center()),run_time=1.0,rate_func=linear)
  self.play(FadeOut(req),run_time=.2)
  book2=VGroup(RoundedRectangle(width=.48,height=.65,corner_radius=.06,fill_color=TEAL,fill_opacity=1,stroke_width=0),Line(UP*.23+LEFT*.12,DOWN*.23+LEFT*.12,color=BG,stroke_width=2)).move_to(source.get_center())
  self.play(FadeIn(book2,scale=.7),run_time=.3)
  self.play(book2.animate.move_to(cache.get_center()+UP*.12),run_time=1.0,rate_func=smooth)
  stored=book2.copy()
  self.add(stored)
  self.play(book2.animate.move_to(reader.get_center()+DOWN*.25),run_time=1.0,rate_func=smooth)
  self.play(FadeOut(cap2),run_time=.2)
  cap3=txt('取回后留一份，下次就能直接拿',31).move_to(DOWN*2.35)
  self.play(FadeIn(cap3),run_time=.35); self.wait(2.6)
  self.play(FadeOut(VGroup(reader,cache,source,labels,route1,route2,book2,stored,tag2,cap3)),run_time=.6)
  hit=txt('命中',42,TEAL,weight=BOLD).move_to(LEFT*3.15+UP*.35)
  miss=txt('未命中',42,CORAL,weight=BOLD).move_to(RIGHT*3.15+UP*.35)
  a=txt('缓存里有 → 直接返回',28).next_to(hit,DOWN,buff=.4)
  b=txt('缓存里没有 → 去数据源取',28).next_to(miss,DOWN,buff=.4)
  divider=Line(UP*1.25,DOWN*1.15,color=LINE,stroke_width=2)
  note=txt('缓存让重复访问更省时',31,MUTED).move_to(DOWN*2.25)
  self.play(FadeIn(hit),FadeIn(miss),Create(divider),run_time=.6)
  self.play(FadeIn(a),FadeIn(b),FadeIn(note),run_time=.5); self.wait(3.4)
